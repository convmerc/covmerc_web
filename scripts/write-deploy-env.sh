#!/usr/bin/env bash
# Writes .env.production for Firebase Hosting / CI deploys from the current shell env.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/.env.production"

required=(
  NEXT_PUBLIC_FIREBASE_API_KEY
  NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN
  NEXT_PUBLIC_FIREBASE_PROJECT_ID
  NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET
  NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID
  NEXT_PUBLIC_FIREBASE_APP_ID
)

missing=()
for key in "${required[@]}"; do
  if [[ -z "${!key:-}" ]]; then
    missing+=("$key")
  fi
done

if [[ ${#missing[@]} -gt 0 ]]; then
  echo "Missing required env vars: ${missing[*]}" >&2
  exit 1
fi

# OG/social crawlers need a public HTTPS URL — never bake localhost into production builds.
if [[ -z "${NEXT_PUBLIC_SITE_URL:-}" || "${NEXT_PUBLIC_SITE_URL}" == *localhost* || "${NEXT_PUBLIC_SITE_URL}" == *127.0.0.1* ]]; then
  export NEXT_PUBLIC_SITE_URL="${DEPLOY_SITE_URL:-https://convmerc-baeef.web.app}"
fi

{
  echo "# Generated by scripts/write-deploy-env.sh — do not commit"
  for key in "${required[@]}" NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID NEXT_PUBLIC_SITE_URL \
    NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY PAYSTACK_SECRET_KEY PAYSTACK_CALLBACK_URL \
    RESEND_API_KEY ORDER_EMAIL_FROM ORDER_NOTIFICATIONS_TO; do
    if [[ -n "${!key:-}" ]]; then
      printf '%s=%s\n' "$key" "${!key}"
    fi
  done
} >"$OUT"

echo "Wrote ${OUT}"
